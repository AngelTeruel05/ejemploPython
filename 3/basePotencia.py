def basePotencia(b: int, p: int) -> int:
    """
    Calcula la potencia de una base elevada a un exponente.

    Args:
        b (int): La base.
        p (int): El exponente.

    Returns:
        int: El resultado de b elevado a la potencia p.
    """
    return b ** p

print(basePotencia(2, 3))  # Ejemplo de uso, debería imprimir 8